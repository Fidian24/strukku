-- ============================================================================
-- STRUKKU - Skema database utama (PostgreSQL)
-- Sesuai ERD & Data Dictionary pada "Progres Task 2.0" (Lampiran 2).
-- Empat tabel: users, categories, receipts, receipt_items.
--
-- Cara pakai (contoh):
--   createdb strukku
--   psql -d strukku -f database/schema_postgresql.sql
--   psql -d strukku -f database/seed_categories.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- Tabel users: autentikasi & profil pengguna
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE  users               IS 'Data autentikasi dan profil pengguna.';
COMMENT ON COLUMN users.id            IS 'ID unik pengguna (Primary Key).';
COMMENT ON COLUMN users.email         IS 'Alamat email untuk login (unik).';
COMMENT ON COLUMN users.password_hash IS 'Kata sandi yang sudah di-hash (bcrypt/argon2). Jangan pernah simpan password asli.';
COMMENT ON COLUMN users.full_name     IS 'Nama lengkap pengguna.';
COMMENT ON COLUMN users.created_at    IS 'Waktu pendaftaran akun.';

-- ---------------------------------------------------------------------------
-- Tabel categories: kategori standar pengeluaran
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,   -- UNIQUE: tambahan agar seed idempotent
    description TEXT
);

COMMENT ON TABLE  categories             IS 'Daftar kategori standar pengeluaran.';
COMMENT ON COLUMN categories.id          IS 'ID unik kategori (Primary Key).';
COMMENT ON COLUMN categories.name        IS 'Nama kategori (F&B, Kesehatan, Transportasi, Belanja, Lainnya).';
COMMENT ON COLUMN categories.description IS 'Penjelasan singkat kategori.';

-- ---------------------------------------------------------------------------
-- Tabel receipts: data induk (header) satu struk
-- ---------------------------------------------------------------------------
CREATE TABLE receipts (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    merchant_name    VARCHAR(200)   NOT NULL,
    transaction_date TIMESTAMP      NOT NULL,
    total_amount     DECIMAL(15, 2) NOT NULL CHECK (total_amount >= 0),
    image_url        VARCHAR(500),
    created_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE  receipts                  IS 'Data induk transaksi struk hasil ekstraksi OCR.';
COMMENT ON COLUMN receipts.id               IS 'ID unik struk (Primary Key).';
COMMENT ON COLUMN receipts.user_id          IS 'Pemilik struk (Foreign Key ke users). Struk ikut terhapus jika pengguna dihapus.';
COMMENT ON COLUMN receipts.merchant_name    IS 'Nama toko hasil parsing regex OCR (contoh: INDOMARET).';
COMMENT ON COLUMN receipts.transaction_date IS 'Tanggal transaksi dari struk.';
COMMENT ON COLUMN receipts.total_amount     IS 'Total harga struk dalam IDR. DECIMAL (bukan FLOAT) untuk nilai uang.';
COMMENT ON COLUMN receipts.image_url        IS 'Tautan penyimpanan foto struk (boleh kosong).';
COMMENT ON COLUMN receipts.created_at       IS 'Waktu struk dipindai/disimpan.';

-- ---------------------------------------------------------------------------
-- Tabel receipt_items: rincian barang + hasil klasifikasi ML
-- ---------------------------------------------------------------------------
CREATE TABLE receipt_items (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id        INTEGER        NOT NULL REFERENCES receipts(id) ON DELETE CASCADE,
    category_id       INTEGER        NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    item_name         VARCHAR(255)   NOT NULL,
    item_price        DECIMAL(15, 2) NOT NULL CHECK (item_price >= 0),
    confidence_score  REAL           CHECK (confidence_score IS NULL OR (confidence_score >= 0 AND confidence_score <= 1)),
    is_user_corrected BOOLEAN        NOT NULL DEFAULT FALSE
);

COMMENT ON TABLE  receipt_items                   IS 'Rincian barang pada struk beserta prediksi kategori ML (TF-IDF + Multinomial Naive Bayes).';
COMMENT ON COLUMN receipt_items.id                IS 'ID unik item (Primary Key).';
COMMENT ON COLUMN receipt_items.receipt_id        IS 'Struk induk (Foreign Key ke receipts). Item ikut terhapus bersama struk.';
COMMENT ON COLUMN receipt_items.category_id       IS 'Kategori (Foreign Key ke categories). Awalnya prediksi ML, bisa diubah pengguna.';
COMMENT ON COLUMN receipt_items.item_name         IS 'Nama barang mentah dari OCR (contoh: Roti Tawar 500g).';
COMMENT ON COLUMN receipt_items.item_price        IS 'Harga barang dalam IDR.';
COMMENT ON COLUMN receipt_items.confidence_score  IS 'Probabilitas prediksi ML (0..1). NULL jika item ditambahkan manual. Skor rendah ditandai kuning di aplikasi.';
COMMENT ON COLUMN receipt_items.is_user_corrected IS 'TRUE jika pengguna mengganti kategori prediksi. Berguna untuk retraining model.';

-- ---------------------------------------------------------------------------
-- Index untuk kolom relasi & pencarian transaksi
-- ---------------------------------------------------------------------------
-- Riwayat/dashboard: filter per pengguna dan rentang tanggal.
CREATE INDEX idx_receipts_user_date      ON receipts (user_id, transaction_date DESC);
-- Mengambil item milik suatu struk.
CREATE INDEX idx_receipt_items_receipt   ON receipt_items (receipt_id);
-- Agregasi total per kategori.
CREATE INDEX idx_receipt_items_category  ON receipt_items (category_id);
-- Evaluasi/retraining model: cari item yang dikoreksi pengguna.
CREATE INDEX idx_receipt_items_corrected ON receipt_items (is_user_corrected) WHERE is_user_corrected;

COMMIT;
